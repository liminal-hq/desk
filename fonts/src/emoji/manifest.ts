export type Category = keyof typeof CATEGORIES;

/**
 * How much of an emoji is drawn by hand. Every emoji has a hand-drawn 16 × 16 grid.
 *
 * - `core`: also a hand-drawn 12 × 12 and 8 × 8 (the shell's own pictures, in every face down to Desk Small).
 * - `essential`: also a hand-drawn 12 × 12.
 * - `extended`: the 12 × 12 is derived from the 16 × 16 (`derive.ts`), with hand fixes where that fails.
 */
export type Tier = 'core' | 'essential' | 'extended';

export interface Emoji {
  /** The code point: one code point each, no sequences. */
  cp: number;
  /** The emoji as a string, without a variation selector. */
  ch: string;
  /** The CLDR short name, as in Unicode's `emoji-test.txt`. */
  name: string;
  category: Category;
  tier: Tier;
}

const e = (cp: number, name: string, category: Category, tier: Tier): Emoji => ({ cp, ch: String.fromCodePoint(cp), name, category, tier });

