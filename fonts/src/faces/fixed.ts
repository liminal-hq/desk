// Cell rows: 0-2 accents, 3-12 capitals (10 rows), 6-12 the x-height (7 rows), 13-15 descenders.
// Rows are written from the cap height (row 3); `x()` starts at the x-height and `at()` anywhere.
// Most letters sit in columns 1-6 with columns 0 and 7 blank; strokes are one pixel.
const CAP_TOP = 3;
const X_TOP = 6;
const R = (...rows: string[]): string => rows.join('/');
const x = (...rows: string[]): Source => ({ rows: R(...rows), top: X_TOP - CAP_TOP });
const at = (row: number, ...rows: string[]): Source => ({ rows: R(...rows), top: row - CAP_TOP });
/** A full 8 × 16 cell, top row first. */
const cell = (...rows: string[]): Source => at(0, ...rows);
/** The full cell with the given drawing (from `at`) inverted, as code page 437's ◘ and ◙. */
const inverse = (row: number, ...rows: string[]): Source =>
  cell(
    ...Array.from({ length: 16 }, (_, y) =>
      Array.from({ length: 8 }, (_, c) => ((rows[y - row]?.[c] ?? '.') === '#' ? '.' : '#')).join(''),
    ),
  );

